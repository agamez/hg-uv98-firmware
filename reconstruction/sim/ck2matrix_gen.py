#!/usr/bin/env python3
# ck2matrix_gen.py - the CK2 UART command-matrix harness generator (session 71).
#
# Emits ck2matrix-orig.resc + ck2matrix-rec.resc: identical injection
# schedule, identical frame content, per-image RAM dump addresses.
#
# Families (protocol.c routing, GOAL.md 5.5):
#   F1  $A00 neutral 0x216 -> rxBuf full      F6  $B          -> rxBuf2 full
#   F2  $A00 marker  0x216 -> rxBuf full      F7  $C          -> rxBuf2 full
#   F3  $A00 len 0x215     -> REJECT          F8  $A02        -> rxBuf3 full
#   F4  $A01 ok     0x216 -> rxBuf2 full     F9  $A08        -> rxBuf2 5-B PREFIX ONLY
#   F5  $A01 len 0x215     -> REJECT          F10 $A09        -> rxBuf full
#
# Observable per checkpoint: rxBuf[0..15], rxBuf2[0..15], rxBuf3[0..15]
# (the monitor ReadByte lines between the echo markers) + the frame-ready
# flag byte (the orig FLAG_BANK+9 @0x2000509D bit0 / the recon proto_flags).
# Workarounds live only in reconstruction/sim/ per the working rules.

ORIG = dict(
    mach="hguv98-orig",
    rx=0x20003A84, rx2=0x20002F74, rx3=0x20004B94, flag=0x2000509D,
    load=(
        "sysbus WriteDoubleWord 0x00000000 0x20006780\n"
        "sysbus WriteDoubleWord 0x00000004 0x08044691\n"
        "sysbus Tag <0x40021004, 0x40021007> \"RCC_CFGR\" 0x00000008\n"
        "sysbus LoadBinary @/home/sslayer/Proyectos/HG-UV98/firmware/MAIN-MCU-HG-UV98-V1.0.1-190416.bin 0x08004000\n"
        "cpu AddHook 0x08042900 \"from Antmicro.Renode.Peripherals.CPU import RegisterValue; self.SetRegister(9, RegisterValue.Create(0x08040000, 32))\"\n"
        "showAnalyzer sysbus.usart2\n"
    ),
)
REC = dict(
    mach="hguv98-recon",
    rx=0x20001CB8, rx2=0x20001AA0, rx3=0x20001A60, flag=0x20001ED0,
    load=(
        "sysbus WriteDoubleWord 0x00000000 0x20006800\n"
        "sysbus WriteDoubleWord 0x00000004 0x08004165\n"
        "sysbus Tag <0x40021004, 0x40021007> \"RCC_CFGR\" 0x00000008\n"
        "sysbus LoadELF @/home/sslayer/Proyectos/HG-UV98/reconstruction/build/hguv98.elf\n"
        "showAnalyzer sysbus.usart2\n"
    ),
)

# The per-family python injection expressions (the identical content both images).
FRAMES = [
    ("F1_a00_ok",     "f = chr(36)+'A00,' + '0'*14 + ',' + chr(0)*512 + chr(13)+chr(10)"),
    ("F2_a00_marker", "f = chr(36)+'A00,' + '0'*14 + ',' + 'MARKER12' + chr(0)*504 + chr(13)+chr(10)"),
    ("F3_a00_rej",    "f = chr(36)+'A00,' + '0'*14 + ',' + chr(0)*511 + chr(13)+chr(10)"),
    ("F4_a01_ok",     "f = chr(36)+'A01,' + '0'*14 + ',' + ''.join(chr(i & 0xFF) for i in range(512)) + chr(13)+chr(10)"),
    ("F5_a01_rej",    "f = chr(36)+'A01,' + '0'*14 + ',' + chr(0)*511 + chr(13)+chr(10)"),
    ("F6_b_cmd",      "f = chr(36)+'B,HELLO-01' + chr(13)+chr(10)"),
    ("F7_c_cmd",      "f = chr(36)+'C,W,1234' + chr(13)+chr(10)"),
    ("F8_a02_cmd",    "f = chr(36)+'A02,TELEMETRY' + chr(13)+chr(10)"),
    ("F9_a08_cmd",    "f = chr(36)+'A08,BEACONDATA' + chr(13)+chr(10)"),
    ("F10_a09_cmd",   "f = chr(36)+'A09KEYTRIG' + chr(13)+chr(10)"),
]


def emit(cfg, path):
    out = []
    w = out.append
    w("# ck2matrix-%s - the CK2 UART command matrix (generated by ck2matrix_gen.py;\n" % (
        "orig" if cfg is ORIG else "rec"))
    w("# do not edit by hand - regenerate). The stimulus = IDENTICAL to the other\n")
    w("# image: the same 10 frames at the same virtual times, neutral content.\n")
    w("using sysbus\n")
    w('mach create "%s"\n' % cfg["mach"])
    w("machine LoadPlatformDescription @/home/sslayer/Proyectos/HG-UV98/reconstruction/sim/gd32f103.repl\n")
    w(cfg["load"])
    w('echo "=== boot 10 ms ==="\n')
    w('emulation RunFor "00:00:00.010"\n')
    w("sysbus WriteDoubleWord 0xE000E018 0x00000000\n")
    w('echo "=== run to 0.5 s (the boot settle; the ISR receives from here) ==="\n')
    w('emulation RunFor "00:00:00.490"\n')
    for name, expr in FRAMES:
        w('echo "=== inject %s ==="\n' % name)
        w('python "m = emulationManager.CurrentEmulation.Machines[0]; u = m[\'sysbus.usart2\']; %s; assert len(f) >= 11; [u.WriteChar(ord(c)) for c in f]"\n' % expr)
        w('emulation RunFor "00:00:00.300"\n')
        w('echo "=== CK2CHK %s BEGIN ==="\n' % name)
        for a in range(16):
            w("sysbus ReadByte 0x%08X\n" % (cfg["rx"] + a))
        for a in range(16):
            w("sysbus ReadByte 0x%08X\n" % (cfg["rx2"] + a))
        for a in range(16):
            w("sysbus ReadByte 0x%08X\n" % (cfg["rx3"] + a))
        w("sysbus ReadByte 0x%08X\n" % cfg["flag"])
        w('echo "=== CK2CHK %s END ==="\n' % name)
    w('echo "=== run 1 s more ==="\n')
    w('emulation RunFor "00:00:01.000"\n')
    w('echo "=== fault registers (must stay 0) ==="\n')
    w("sysbus ReadDoubleWord 0xE000ED28\n")
    w("sysbus ReadDoubleWord 0xE000ED2C\n")
    with open(path, "w") as fh:
        fh.writelines(out)
    print("wrote", path)


emit(ORIG, "/home/sslayer/Proyectos/HG-UV98/reconstruction/sim/ck2matrix-orig.resc")
emit(REC, "/home/sslayer/Proyectos/HG-UV98/reconstruction/sim/ck2matrix-rec.resc")
